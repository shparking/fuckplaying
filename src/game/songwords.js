// 단어 노래: 이 단어가 들어간 노래를 돌아가며 한 소절씩 (노래는 오프라인으로 부름 — 앱은 단어만 줌)
// 노래 가사에 흔히 나오는 단어들
export const SONG_WORDS = [
  '사랑', '이별', '눈물', '비', '바다', '밤', '별', '달', '하늘', '바람',
  '꽃', '봄', '여름', '가을', '겨울', '눈', '친구', '엄마', '꿈', '시간',
  '오늘', '내일', '마음', '노래', '춤', '술', '사람', '행복', '손', '길',
  '기억', '미소', '그대', '안녕', '하루', '거리', '빛', '태양', '기차', '전화',
  '편지', '사진', '커피', '청춘', '영원', '아침', '새벽', '구름', '고백', '약속',
  '이름', '바보', '미안', '고마워', '집', '첫사랑', '비행기', '파도', '소녀', '우산',
  '생일', '크리스마스', '토요일', '향기', '심장', '천국', '운명', '자동차', '바다', '불꽃',
].filter((w, i, a) => a.indexOf(w) === i)

// 최근에 나온 단어(used)는 빼고 하나 (다 나왔으면 아무거나)
export function pickSongWord(used = [], rand = Math.random) {
  const pool = SONG_WORDS.filter((w) => !used.includes(w))
  const list = pool.length ? pool : SONG_WORDS
  return list[Math.floor(rand() * list.length)]
}
