// 직전 키워드와 다른 걸로
export function pickNhaengWord(prev) {
  let w
  do w = NHAENG_WORDS[Math.floor(Math.random() * NHAENG_WORDS.length)]
  while (w === prev && NHAENG_WORDS.length > 1)
  return w
}
